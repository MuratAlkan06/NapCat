// NapCatWire — F4 remote approvals: the lifecycle of ONE permission prompt on
// the Mac, from the gate to a terminal state. Design:
// design/remote-approvals.md (timeouts, race, kill switch, audit).
//
// PURE — no imports, no I/O, no clock: every event carries `now`, in seconds
// on a monotonic clock the caller owns, and the machine only returns the
// effects for the caller to perform and the audit entries to log. It never
// answers a dialog on its own: the ONE `.deliverVerdict` is the acceptance of
// a valid remote decision for this prompt inside its TTL (lint-locked).
// Expiry, the kill switch and a session ending only withdraw the record; the
// local dialog stays open and keeps full capability throughout.

/// A prompt's random 128-bit ID, the name of its CloudKit record. This is a
/// type only: the ID is generated by the caller from a cryptographic source.
public struct PromptID: Hashable, Sendable, CustomStringConvertible {
    public let high: UInt64
    public let low: UInt64

    /// nil for the all-zero ID, which marks an unset value, never a random one.
    public init?(high: UInt64, low: UInt64) {
        guard high != 0 || low != 0 else { return nil }
        self.high = high
        self.low = low
    }

    /// The record-name form: exactly `ApprovalWire.promptIDHexDigits`
    /// LOWERCASE hex digits, nothing else (one ID, one spelling).
    public init?(hex: String) {
        let digits = Array(hex.utf8)
        guard digits.count == ApprovalWire.promptIDHexDigits else { return nil }
        var halves: [UInt64] = [0, 0]
        for (offset, byte) in digits.enumerated() {
            let value: UInt8
            if byte >= UInt8(ascii: "0") && byte <= UInt8(ascii: "9") {
                value = byte - UInt8(ascii: "0")
            } else if byte >= UInt8(ascii: "a") && byte <= UInt8(ascii: "f") {
                value = byte - UInt8(ascii: "a") + 10
            } else {
                return nil
            }
            let half = offset < ApprovalWire.promptIDHexDigits / 2 ? 0 : 1
            halves[half] = halves[half] << 4 | UInt64(value)
        }
        self.init(high: halves[0], low: halves[1])
    }

    public var hex: String { Self.padded(high) + Self.padded(low) }

    public var description: String { hex }

    private static func padded(_ half: UInt64) -> String {
        let digits = String(half, radix: 16)
        return String(repeating: "0", count: ApprovalWire.promptIDHexDigits / 2 - digits.count) + digits
    }
}

/// A decision record as the Mac read it, after the caller checked its
/// signature against the paired phone's Secure Enclave key (CL-1).
public struct ApprovalDecision: Equatable, Sendable {
    public let promptID: PromptID
    public let verdict: ApprovalWire.Verdict
    public let wireVersion: Int
    /// Whether the signature verified. An unverified decision is ignored.
    public let signatureVerified: Bool

    public init(promptID: PromptID, verdict: ApprovalWire.Verdict, wireVersion: Int, signatureVerified: Bool) {
        self.promptID = promptID
        self.verdict = verdict
        self.wireVersion = wireVersion
        self.signatureVerified = signatureVerified
    }
}

/// What can happen to a prompt after it opened.
public enum ApprovalEvent: Equatable, Sendable {
    /// CloudKit accepted the prompt record.
    case saveAccepted
    /// The prompt record could not be saved.
    case saveFailed
    /// A decision record arrived from the phone.
    case remoteDecision(ApprovalDecision)
    /// The dialog was answered at the Mac (the session moved on).
    case answeredLocally
    /// Time passed (lets the TTL run out with nothing else happening).
    case tick
    /// The Mac toggle went off.
    case killSwitch
    /// The session that owned the dialog ended.
    case sessionEnded
}

/// Why a prompt never left the Mac.
public enum ApprovalHold: Equatable, Sendable {
    /// The category gate kept it.
    case gate(ApprovalSuppression)
    /// The feature is not enabled on both devices (or the relay is not
    /// available), so nothing is forwarded at all.
    case notArmed
}

/// Who answered a forwarded prompt first.
public enum ApprovalResolution: Equatable, Sendable {
    case remote(ApprovalWire.Verdict)
    /// The local verdict is not visible to NapCat; only that it came first.
    case local
}

/// Why a pending prompt was withdrawn without an answer.
public enum ApprovalRetraction: String, CaseIterable, Sendable {
    case killSwitch
    case sessionEnded
}

/// Why a decision had no effect (the "loser" the audit log records).
public enum ApprovalIgnoreReason: String, CaseIterable, Sendable {
    /// For another prompt.
    case wrongPrompt
    case wrongWireVersion
    /// Its signature did not verify.
    case unauthenticated
    /// This prompt was never (or not yet) forwarded.
    case notForwarded
    /// Another decision came first.
    case alreadyResolved
    /// The TTL ran out first.
    case expired
    /// The kill switch or the session's end came first.
    case retracted
}

/// Where one prompt is.
public enum ApprovalPhase: Equatable, Sendable {
    /// Never left the Mac (terminal).
    case suppressed(ApprovalHold)
    /// The record is being saved.
    case saving
    /// The record is in CloudKit; the phone may answer until `expiresAt`.
    case forwarded
    /// The save failed; the prompt is local-only (terminal).
    case forwardFailed
    /// Answered (terminal).
    case resolved(ApprovalResolution)
    /// The TTL ran out unanswered (terminal).
    case expired
    /// Withdrawn unanswered (terminal).
    case retracted(ApprovalRetraction)

    /// Whether nothing remote can change this prompt any more.
    public var isTerminal: Bool {
        switch self {
        case .saving, .forwarded: return false
        case .suppressed, .forwardFailed, .resolved, .expired, .retracted: return true
        }
    }
}

/// Work for the caller. The machine itself does none of it.
public enum ApprovalEffect: Equatable, Sendable {
    /// Write the prompt record.
    case saveRecord
    /// The forward was accepted: the actionable push replaces the plain
    /// waiting alert for this episode (only now, never before the save).
    case supersedeWaitingAlert
    /// Resolve the open dialog with this verdict.
    case deliverVerdict(ApprovalWire.Verdict)
    /// Delete the prompt record (and its decision, if any).
    case retractRecord
}

/// One audit-log entry: a closed vocabulary, never prompt content.
public enum ApprovalAudit: Equatable, Sendable {
    case suppressed(ApprovalHold)
    case forwarded
    case forwardFailed
    case decided(ApprovalResolution)
    case ignored(ApprovalIgnoreReason)
    case expired
    case retracted(ApprovalRetraction)
}

/// What one event did.
public struct ApprovalTransition: Equatable, Sendable {
    public let effects: [ApprovalEffect]
    public let audit: [ApprovalAudit]

    public init(effects: [ApprovalEffect], audit: [ApprovalAudit]) {
        self.effects = effects
        self.audit = audit
    }

    /// Nothing happened.
    public static let none = ApprovalTransition(effects: [], audit: [])
}

/// The lifecycle of one prompt. A decision only ever affects the prompt whose
/// ID it carries; the caller keeps one lifecycle per open dialog.
public struct ApprovalLifecycle: Equatable, Sendable {
    public let id: PromptID
    /// When the prompt opened, in the caller's monotonic seconds.
    public let createdAt: Int
    public private(set) var phase: ApprovalPhase

    /// The end of the remote window: `createdAt` + the wire's TTL.
    public var expiresAt: Int { createdAt + ApprovalWire.promptTimeToLiveSeconds }

    private init(id: PromptID, createdAt: Int, phase: ApprovalPhase) {
        self.id = id
        self.createdAt = createdAt
        self.phase = phase
    }

    /// A prompt opens with the gate's answer. It is forwarded only when the
    /// gate forwards it AND the feature is armed on both devices.
    public static func open(id: PromptID, classification: ApprovalClassification, armed: Bool, now: Int)
        -> (lifecycle: ApprovalLifecycle, transition: ApprovalTransition) {
        let hold: ApprovalHold
        switch (armed, classification) {
        case (true, .forward):
            return (ApprovalLifecycle(id: id, createdAt: now, phase: .saving),
                    ApprovalTransition(effects: [.saveRecord], audit: []))
        case (false, _):
            hold = .notArmed
        case (true, .suppress(let suppression)):
            hold = .gate(suppression)
        }
        return (ApprovalLifecycle(id: id, createdAt: now, phase: .suppressed(hold)),
                ApprovalTransition(effects: [], audit: [.suppressed(hold)]))
    }

    public mutating func apply(_ event: ApprovalEvent, now: Int) -> ApprovalTransition {
        switch event {
        case .remoteDecision(let decision): return decide(decision, now: now)
        case .saveAccepted: return saveAccepted(now: now)
        case .saveFailed: return saveFailed()
        case .answeredLocally: return answeredLocally()
        case .tick: return tick(now: now)
        case .killSwitch: return retract(.killSwitch)
        case .sessionEnded: return retract(.sessionEnded)
        }
    }

    /// Identity, version and signature first (whatever the phase), then the
    /// phase and the TTL on the Mac's clock. First decision wins.
    private mutating func decide(_ decision: ApprovalDecision, now: Int) -> ApprovalTransition {
        guard decision.promptID == id else { return Self.ignored(.wrongPrompt) }
        guard decision.wireVersion == ApprovalWire.wireVersion else { return Self.ignored(.wrongWireVersion) }
        guard decision.signatureVerified else { return Self.ignored(.unauthenticated) }
        switch phase {
        case .forwarded:
            guard now < expiresAt else {
                phase = .expired
                return ApprovalTransition(effects: [.retractRecord], audit: [.expired, .ignored(.expired)])
            }
            phase = .resolved(.remote(decision.verdict))
            return ApprovalTransition(effects: [.deliverVerdict(decision.verdict), .retractRecord],
                                      audit: [.decided(.remote(decision.verdict))])
        case .saving, .suppressed, .forwardFailed: return Self.ignored(.notForwarded)
        case .resolved: return Self.ignored(.alreadyResolved)
        case .expired: return Self.ignored(.expired)
        case .retracted: return Self.ignored(.retracted)
        }
    }

    /// Accepted in time: forwarded, and only now the waiting alert yields.
    /// Accepted after the prompt stopped mattering: delete the late record.
    private mutating func saveAccepted(now: Int) -> ApprovalTransition {
        switch phase {
        case .saving:
            guard now < expiresAt else {
                phase = .expired
                return ApprovalTransition(effects: [.retractRecord], audit: [.expired])
            }
            phase = .forwarded
            return ApprovalTransition(effects: [.supersedeWaitingAlert], audit: [.forwarded])
        case .resolved, .expired, .retracted, .forwardFailed:
            return ApprovalTransition(effects: [.retractRecord], audit: [])
        case .forwarded, .suppressed:
            return .none
        }
    }

    /// The prompt stays local-only and the plain waiting alert is not
    /// superseded (no silent loss of the buzz).
    private mutating func saveFailed() -> ApprovalTransition {
        switch phase {
        case .saving:
            phase = .forwardFailed
            return ApprovalTransition(effects: [], audit: [.forwardFailed])
        case .forwarded, .suppressed, .forwardFailed, .resolved, .expired, .retracted:
            return .none
        }
    }

    /// The local answer came first while the prompt was out.
    private mutating func answeredLocally() -> ApprovalTransition {
        switch phase {
        case .saving, .forwarded:
            phase = .resolved(.local)
            return ApprovalTransition(effects: [.retractRecord], audit: [.decided(.local)])
        case .suppressed, .forwardFailed, .resolved, .expired, .retracted:
            return .none
        }
    }

    /// The TTL ran out: withdraw the record, answer nothing.
    private mutating func tick(now: Int) -> ApprovalTransition {
        switch phase {
        case .saving, .forwarded:
            guard now >= expiresAt else { return .none }
            phase = .expired
            return ApprovalTransition(effects: [.retractRecord], audit: [.expired])
        case .suppressed, .forwardFailed, .resolved, .expired, .retracted:
            return .none
        }
    }

    private mutating func retract(_ reason: ApprovalRetraction) -> ApprovalTransition {
        switch phase {
        case .saving, .forwarded:
            phase = .retracted(reason)
            return ApprovalTransition(effects: [.retractRecord], audit: [.retracted(reason)])
        case .suppressed, .forwardFailed, .resolved, .expired, .retracted:
            return .none
        }
    }

    private static func ignored(_ reason: ApprovalIgnoreReason) -> ApprovalTransition {
        ApprovalTransition(effects: [], audit: [.ignored(reason)])
    }
}
